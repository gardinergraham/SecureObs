const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const output = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/utils/wardStaffAssignment.ts','utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText,{ exports: output });
const sally={id:'sally',organisationId:'company-a',name:'Sally Jones',staffCode:'SJ01',role:'nurse',wardId:'ward-2',allowedWardIds:['ward-2'],allowedSiteIds:['site-a'],wardRoles:{'ward-2':'nurse'},canPrescribe:true,active:true};
const ward={id:'ward-1',organisationId:'company-a',siteId:'site-a'};
const manager=output.assignStaffWardRole(sally,ward,'manager');
assert.equal(manager.id,sally.id);
assert.equal(manager.staffCode,sally.staffCode);
assert.equal(manager.wardRoles['ward-1'],'manager');
assert.equal(manager.wardRoles['ward-2'],'nurse');
assert.equal(manager.canPrescribe,true);
assert.equal(manager.wardId,'ward-2');
assert.equal(manager.allowedWardIds.length,2);
assert.equal(output.assignStaffWardRole(manager,ward,'manager').allowedWardIds.length,2);
assert.equal(sally.allowedWardIds.length,1);
assert.equal(output.assignStaffWardRole(manager,ward,'nurse').wardRoles['ward-2'],'nurse');
assert.throws(()=>output.assignStaffWardRole(sally,{...ward,organisationId:'company-b'},'manager'));
console.log('PASS: promote existing Sally without duplication, preserve other ward roles, identity and prescribing; demote only selected ward; reject another company.');
